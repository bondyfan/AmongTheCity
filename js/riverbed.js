let RUNS = null;     // gz -> [gx0, gx1, gx0, gx1, ...], parsed on first use
function runs() {
  if (RUNS) return RUNS;
  RUNS = new Map();
  for (const row of MASK.split(';')) {
    const [gz, list] = row.split(':');
    const out = [];
    for (const r of list.split(',')) {
      const [a, b] = r.split('~');
      out.push(+a, b === undefined ? +a : +b);
    }
    RUNS.set(+gz, out);
  }
  return RUNS;
}

/**
 * Lower the riverbed samples of one height-map tile in place. `g` is the
 * tile's Int16Array (decimetres), `n` samples per side, `res` metres between
 * them, tile origin at (tx * tile, tz * tile). Returns how many moved.
 */
export function riverbedInto(g, tx, tz, n, res, tile) {
  const R = runs();
  const gx0 = Math.round(tx * tile / res), gz0 = Math.round(tz * tile / res);
  let moved = 0;
  for (let j = 0; j < n; j++) {
    const list = R.get(gz0 + j);
    if (!list) continue;
    for (let k = 0; k < list.length; k += 2) {
      const a = Math.max(list[k], gx0), b = Math.min(list[k + 1], gx0 + n - 1);
      for (let gx = a; gx <= b; gx++) {
        const lv = poolLevelAt(gx * res, (gz0 + j) * res);
        if (lv === null) continue;
        const o = j * n + (gx - gx0), v = Math.round((lv - DEPTH) * 10);
        if (g[o] !== -32768 && v < g[o]) { g[o] = v; moved++; }
      }
    }
  }
  return moved;
}
