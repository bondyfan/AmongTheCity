/** kit.ground is 0 here: every height is absolute. */
export function hradFar(kit) {
  const S = (r) => { let a = 0; for (let i = 0; i < r.length; i++) { const p = r[i], q = r[(i + 1) % r.length]; a += p[0] * q[1] - q[0] * p[1]; } return a > 0 ? 1 : -1; };
  const E = HRAD_CORNICE;
  const rows = (y0) => {
    const out = [];
    for (let top = E - 1.6, i = 0; i < 6; i++, top -= 3.8) if (top - 2.2 - y0 > 1) out.push({ y: top - 2.2 - y0, h: 2.2, w: 1.6, hex: PANE, glow: 0.2, rev: 0 });
    return out.reverse();
  };
  const walls = (ring, hole) => {
    const s = S(ring) * (hole ? -1 : 1);
    for (let i = 0; i < ring.length; i++) {
      const a = ring[i], b = ring[(i + 1) % ring.length];
      const ex = b[0] - a[0], ez = b[1] - a[1], L = Math.hypot(ex, ez);
      if (L < 0.05) continue;
      const y0 = Math.min(a[2], b[2]) - 1.5;
      kit.wallGrid([a[0], a[1]], [b[0], b[1]], y0, E, s * ez / L, -s * ex / L, L < 6 ? { cols: 1, rows: [] } : { pitch: 5.2, inset: 0.8, rows: rows(y0), seed: i });
    }
  };
  kit.set(WALL, K.plaster);
  walls(OUTER, false);
  walls(COURT, true);
  kit.set(ROOF, K.copper);
  const xz = (r) => r.map((p) => [p[0], p[1]]);
  ringRoof(kit, xz(OUTER), [xz(COURT)], E, 6, 5.5, 0.45);
}
